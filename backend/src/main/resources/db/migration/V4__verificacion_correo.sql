-- Verificación del correo electrónico.
-- Las cuentas que ya existen se dan por verificadas (DEFAULT TRUE) para no dejar fuera a nadie; el código
-- marca como no verificadas las que se registran a partir de ahora.
ALTER TABLE usuario ADD COLUMN correo_verificado BOOLEAN NOT NULL DEFAULT TRUE;

-- Igual que token_recuperacion: solo se guarda el hash SHA-256 del token, que viaja en el enlace del correo.
CREATE TABLE token_verificacion_correo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario (usuario_id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expira_en TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_token_verificacion_usuario ON token_verificacion_correo (usuario_id);
