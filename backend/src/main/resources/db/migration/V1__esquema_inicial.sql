-- Línea base del esquema, equivalente a lo que generan las entidades JPA.
-- En una base que ya tiene tablas Flyway la marca como aplicada (baseline-on-migrate) y no la ejecuta.

CREATE TABLE usuario (
    usuario_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario VARCHAR(255) NOT NULL UNIQUE,
    correo_electronico VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    saldo DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    puntos INT NOT NULL DEFAULT 0,
    pais VARCHAR(255) NOT NULL,
    ciudad VARCHAR(255) NOT NULL,
    codigo_postal VARCHAR(255) NOT NULL,
    calle VARCHAR(255) NOT NULL,
    numero_piso INT NOT NULL DEFAULT 0,
    letra_piso VARCHAR(10) DEFAULT '',
    privacidad_anonimo_pujas BOOLEAN NOT NULL DEFAULT FALSE,
    privacidad_estadisticas BOOLEAN NOT NULL DEFAULT TRUE,
    privacidad_perfil_visible BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE token_recuperacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario (usuario_id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expira_en TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE trabajador (
    trabajador_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario VARCHAR(255) NOT NULL UNIQUE,
    correo_electronico VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    rol_trabajador BOOLEAN NOT NULL DEFAULT TRUE -- TRUE = experto, FALSE = administrador
);

CREATE TABLE subasta (
    subasta_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicial DATE NOT NULL,
    fecha_final DATE NOT NULL,
    precio_inicial DECIMAL(10,2) DEFAULT 0.00,
    precio_final DECIMAL(10,2) DEFAULT 0.00,
    subasta_normal BOOLEAN NOT NULL,
    nombre_articulo VARCHAR(255) NOT NULL,
    descripcion TEXT NOT NULL,
    imagen VARCHAR(255),
    creador_id BIGINT NOT NULL REFERENCES usuario (usuario_id),
    ganador_id BIGINT REFERENCES usuario (usuario_id),
    categoria VARCHAR(255) NOT NULL
);

CREATE TABLE puja (
    puja_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    importe DECIMAL(10,2) NOT NULL,
    ganadora BOOLEAN NOT NULL DEFAULT FALSE,
    usuario_id BIGINT NOT NULL REFERENCES usuario (usuario_id),
    subasta_id BIGINT NOT NULL REFERENCES subasta (subasta_id)
);

CREATE TABLE comentario (
    comentario_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comentario TEXT NOT NULL,
    precio_estimado DECIMAL(10,2) NOT NULL,
    trabajador_id BIGINT NOT NULL REFERENCES trabajador (trabajador_id),
    subasta_id BIGINT NOT NULL REFERENCES subasta (subasta_id)
);

CREATE TABLE sorteo (
    sorteo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_articulo VARCHAR(255) NOT NULL,
    descripcion TEXT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    puntos_necesarios INT NOT NULL,
    puntos_finales INT NOT NULL DEFAULT 0,
    trabajador_id BIGINT NOT NULL REFERENCES trabajador (trabajador_id),
    ganador_id BIGINT REFERENCES usuario (usuario_id),
    imagen VARCHAR(255) NOT NULL,
    categoria VARCHAR(255) NOT NULL
);

CREATE TABLE puja_sorteo (
    puja_sorteo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    puntos DECIMAL(10,2) NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuario (usuario_id),
    sorteo_id BIGINT NOT NULL REFERENCES sorteo (sorteo_id)
);
